const ZONE_PREFIXES: [string, string][] = [
  ["Australia/", "AU"],
  ["America/Argentina/", "AR"],
  ["America/Indiana/", "US"],
  ["America/Kentucky/", "US"],
  ["America/North_Dakota/", "US"],
]

const known = new Set(countries.map((country) => country.code))

/**
 * Best guess at where this device is, as an ISO code on our list — from
 * the time zone first, then the region in the browser's languages
 * (`en-IN` → IN). "" when neither says anything we can use.
 */
export function detectCountry(): string {
  try {
    const zone = Intl.DateTimeFormat().resolvedOptions().timeZone
    const byZone = ZONES[zone] ?? ZONE_PREFIXES.find(([prefix]) => zone.startsWith(prefix))?.[1]
    if (byZone && known.has(byZone)) return byZone
  } catch {
    // No Intl time zone support — fall through to the language.
  }
  for (const language of typeof navigator === "undefined" ? [] : navigator.languages) {
    const region = language.split("-")[1]?.toUpperCase()
    if (region && known.has(region)) return region
  }
  return ""
}
